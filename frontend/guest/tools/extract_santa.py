#!/usr/bin/env python3
"""Regenerates guest/src/santa-art.ts from Mira's pa10a mockups (design READY, lint PASS).

- Santa: the real ModernAvatar export with pa10a/src/santa-sprite.ts applied (pa10a/src/parts.json, from
  render_parts.py). The frame and mood badges are the same rects as the Quizmaster's (art.ts QM_FRAME, MOOD_*),
  checked below, so only the body is new: the 64 px body and the 1.2x zoomed body ModernAvatar uses under 48 px.
- The pixel gift box and its lid (guest-390.html `.giftbox`, red and yellow avatar palettes).
- Pixel icons the Santa screens add: gift, send, arrow.

Usage: python3 -I frontend/guest/tools/extract_santa.py <pa10a folder> > frontend/guest/src/santa-art.ts
"""
import json, re, sys

src = sys.argv[1]
parts = json.load(open(f'{src}/src/parts.json'))
page = open(f'{src}/guest-390.html').read()
palette = []


def col(c):
    if c is None:
        return -1
    if c not in palette:
        palette.append(c)
    return palette.index(c)


def rects(svg):
    out = []
    for r in re.findall(r'<rect[^>]*>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', r))
        nums = [float(a[k]) for k in ('x', 'y', 'width', 'height')]
        nums = [int(n) if n == int(n) else n for n in nums]
        out.append(nums + [col(a.get('fill'))])
    return out


def body(svg):
    return re.search(r'kw-avatar-body">(.*?)</g>', svg, flags=re.S).group(1)


big = parts['sa_64_idle']
small = parts['sa_28_idle']
frame = big[big.index('<svg'):big.index('<g')]
assert frame.count('<rect') == 24, 'Santa frame changed: compare with QM_FRAME'
transform = re.search(r'<g transform="([^"]*)"', small).group(1)

gift = re.search(r'<svg class="giftbox[^"]*".*?</svg>', page, flags=re.S).group(0)
lid = re.search(r'<g class="lid">(.*?)</g>', gift, flags=re.S).group(1)
box = gift[gift.index('</g>') + 4:gift.index('</svg>')]


def icon_after(marker):
    i = page.index(marker)
    j = page.index('<svg', i)
    s = page[j:page.index('</svg>', j) + 6]
    return re.search(r'viewBox="([^"]*)"', s).group(1), rects(s)


icons = {
    'gift': icon_after('<div class="eyebrow">'),
    'send': icon_after('<div class="send" aria-label="Send">'),
    'arrow': icon_after('<span class="ar">'),
}
tables = {'SA_BODY': rects(body(big)), 'SA_BODY_SMALL': rects(body(small)), 'GIFT_LID': rects(lid), 'GIFT_BOX': rects(box)}
compact = dict(separators=(',', ':'))
print('// Generated by guest/tools/extract_santa.py from the pa10a mockups. Do not edit by hand.')
print('// A rect is [x, y, w, h, colour index into SA_PALETTE] (-1 = currentColor). Frame and mood badges: art.ts.')
print("import type { Rects } from './art';")
print(f'export const SA_PALETTE: string[] = {json.dumps(palette)};')
for k, v in tables.items():
    print(f'export const {k}: Rects = {json.dumps(v, **compact)};')
print(f'export const SA_SMALL_TRANSFORM = {json.dumps(transform)};')
print('export const SA_ICONS: Record<string, [string, Rects]> = {')
for k, (vb, rs) in icons.items():
    print(f'  {k}: [{json.dumps(vb)}, {json.dumps(rs, **compact)}],')
print('};')
