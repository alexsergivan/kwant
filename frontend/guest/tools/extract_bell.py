#!/usr/bin/env python3
"""Regenerates guest/src/desk/bell-art.ts from Mira's pa13 export (design READY, Mockup lint: PASS).

- Bell: the real ModernAvatar (desk style, teal body, `bell` overlay from pa13/src/bell-sprite.ts), taken from
  pa13/src/parts.json. Frame and the thinking/finished badges are the Quizmaster's (art.ts QM_FRAME, MOOD_*), checked
  below, so only the body is new: the 64 px body, the 1.2x zoomed body ModernAvatar uses under 48 px, and the
  `failed` badge (G10: Bell can't answer).
- The pixel icons the desk screens use, from the patterns in pa13/src/gen.py (PXI).

Usage: python3 -I frontend/guest/tools/extract_bell.py <pa13 folder> [mockup-kit/avatars.py] > frontend/guest/src/desk/bell-art.ts
"""
import ast, json, re, sys

src = sys.argv[1]
parts = json.load(open(f'{src}/src/parts.json'))
gen = open(f'{src}/src/gen.py').read()
palette = []


def col(c):
    if c is None:
        return -1
    if c not in palette:
        palette.append(c)
    return palette.index(c)


def rects(svg):
    out = []
    for r in re.findall(r'<rect[^>]*>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', r))
        nums = [float(a[k]) for k in ('x', 'y', 'width', 'height')]
        nums = [int(n) if n == int(n) else n for n in nums]
        out.append(nums + [col(a.get('fill'))])
    return out


def body(svg):
    return re.search(r'kw-avatar-body">(.*?)</g></g>', svg, flags=re.S).group(1) if 'kw-avatar-body"><g' in svg else re.search(r'kw-avatar-body">(.*?)</g>', svg, flags=re.S).group(1)


big = parts['bl_64_idle']
small = parts['bl_28_idle']
frame = big[big.index('<svg'):big.index('<g')]
assert frame.count('<rect') == 24, 'Bell frame changed: compare with QM_FRAME'
transform = re.search(r'<g transform="([^"]*)"', small).group(1)
failed = parts['bl_64_failed']
badge = failed[failed.rindex('<svg'):]
assert 'data-mood="failed"' in badge

block = gen[gen.index('PXI.update(') + len('PXI.update('):]
block = block[:block.index('})') + 1]
pats = ast.literal_eval(block)
# The moon (G7, G10 notes) is a mockup-kit icon that gen.py takes from avatars.IC rather than PXI.
kit = open(sys.argv[2] if len(sys.argv) > 2 else '/home/maus/shared/ship-software-safely/mockup-kit/avatars.py').read()
pats.setdefault('moon', ast.literal_eval(re.search(r'"moon": (\[[^\]]*\])', kit).group(1)))


def icon(rows):
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == '#':
                s = x
                while x < len(row) and row[x] == '#':
                    x += 1
                out.append([s, y, x - s, 1, -1])
            else:
                x += 1
    return f'0 0 {max(len(r) for r in rows)} {len(rows)}', out


compact = dict(separators=(',', ':'))
print('// Generated by guest/tools/extract_bell.py from the pa13 export. Do not edit by hand.')
print('// A rect is [x, y, w, h, colour index into BL_PALETTE] (-1 = currentColor). Frame and the other mood badges: art.ts.')
print("import type { Rects } from '../art';")
b, s, f = rects(body(big)), rects(body(small)), rects(badge)
print(f'export const BL_PALETTE: string[] = {json.dumps(palette)};')
print(f'export const BL_BODY: Rects = {json.dumps(b, **compact)};')
print(f'export const BL_BODY_SMALL: Rects = {json.dumps(s, **compact)};')
print(f'export const BL_SMALL_TRANSFORM = {json.dumps(transform)};')
print(f'export const MOOD_FAILED: Rects = {json.dumps(f, **compact)};')
print('export const DESK_ICONS: Record<string, [string, Rects]> = {')
for k in ('lock', 'clock', 'retry', 'warn', 'send', 'bell', 'chat', 'nowifi', 'door', 'bot', 'person', 'moon'):
    vb, rs = icon(pats[k])
    print(f'  {k}: [{json.dumps(vb)}, {json.dumps(rs, **compact)}],')
print('};')
