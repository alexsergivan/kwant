#!/usr/bin/env python3
"""Regenerates guest/src/tally-art.ts from Mira's pa10b mockups (design READY, lint PASS).

- Tally: the real ModernAvatar export with pa10b/src/tally-sprite.ts applied (pa10b/src/parts.json). The frame and
  mood badges are the Quizmaster's (art.ts QM_FRAME, MOOD_*), checked below, so only the body is new: the 64 px body
  and the 1.2x zoomed body ModernAvatar uses under 48 px.
- Pixel icons the gather screens add (guest-390.html): eye (who sees), minus (stepper), up, down (ranking), trophy
  (the club picked).

Usage: python3 -I frontend/guest/tools/extract_tally.py <pa10b folder> > frontend/guest/src/tally-art.ts
"""
import json, re, sys

src = sys.argv[1]
parts = json.load(open(f'{src}/src/parts.json'))
page = open(f'{src}/guest-390.html').read()
palette = []


def col(c):
    if c is None:
        return -1
    if c not in palette:
        palette.append(c)
    return palette.index(c)


def rects(svg):
    out = []
    for r in re.findall(r'<rect[^>]*>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', r))
        nums = [float(a[k]) for k in ('x', 'y', 'width', 'height')]
        nums = [int(n) if n == int(n) else n for n in nums]
        out.append(nums + [col(a.get('fill'))])
    return out


def body(svg):
    return re.search(r'kw-avatar-body">(.*?)</g>', svg, flags=re.S).group(1)


big = parts['ta_64_idle']
small = parts['ta_28_idle']
frame = big[big.index('<svg'):big.index('<g')]
assert frame.count('<rect') == 24, 'Tally frame changed: compare with QM_FRAME'
transform = re.search(r'<g transform="([^"]*)"', small).group(1)


def icon_after(marker):
    i = page.index(marker)
    j = page.index('<svg', i)
    s = page[j:page.index('</svg>', j) + 6]
    return re.search(r'viewBox="([^"]*)"', s).group(1), rects(s)


icons = {
    'eye': icon_after('<div class="whosees">'),
    'minus': icon_after('<div class="sb" aria-label="One fewer">'),
    'up': icon_after('aria-label="Move The Old Mill up"'),
    'down': icon_after('aria-label="Move The Old Mill down"'),
    'trophy': icon_after('<div class="eyebrow">'),
}
tables = {'TA_BODY': rects(body(big)), 'TA_BODY_SMALL': rects(body(small))}
compact = dict(separators=(',', ':'))
print('// Generated by guest/tools/extract_tally.py from the pa10b mockups. Do not edit by hand.')
print('// A rect is [x, y, w, h, colour index into TA_PALETTE] (-1 = currentColor). Frame and mood badges: art.ts.')
print("import type { Rects } from './art';")
print(f'export const TA_PALETTE: string[] = {json.dumps(palette)};')
for k, v in tables.items():
    print(f'export const {k}: Rects = {json.dumps(v, **compact)};')
print(f'export const TA_SMALL_TRANSFORM = {json.dumps(transform)};')
print('export const GA_ICONS: Record<string, [string, Rects]> = {')
for k, (vb, rs) in icons.items():
    print(f'  {k}: [{json.dumps(vb)}, {json.dumps(rs, **compact)}],')
print('};')
