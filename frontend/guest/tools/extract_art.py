#!/usr/bin/env python3
"""Regenerates guest/src/art.ts from Mira's pa0a guest mockups (design READY, lint PASS).

The mockups carry the real ModernAvatar Quizmaster export (kwant main + pa0a/src/quizmaster-sprite.ts), the kit's
eight `avatars.char` creatures and the pixel icons, as plain <rect> lists. This turns them into compact rect tables
the guest page draws with createElementNS: no React, no innerHTML.

Usage: python3 -I frontend/guest/tools/extract_art.py <pa0a folder> > frontend/guest/src/art.ts
"""
import json, re, sys

src = sys.argv[1]
join = open(f'{src}/guest-join-390.html').read()
play = open(f'{src}/guest-play-390.html').read()
palette = []


def col(c):
    if c is None:
        return -1
    if c not in palette:
        palette.append(c)
    return palette.index(c)


def rects(svg):
    out = []
    for r in re.findall(r'<rect[^>]*>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', r))
        nums = [float(a[k]) for k in ('x', 'y', 'width', 'height')]
        nums = [int(n) if n == int(n) else n for n in nums]
        out.append(nums + [col(a.get('fill'))])
    return out


def svg_after(html, marker):
    i = html.index(marker)
    j = html.index('<svg', i)
    return html[j:html.index('</svg>', j) + 6]


def vb(svg):
    return re.search(r'viewBox="([^"]*)"', svg).group(1)


# Quizmaster at 64 px (the larger export: it has the shadow line the 28 px one drops)
avatars = [m.group(1) for m in re.finditer(r'<div class="kw-avatar[^>]*>(.*?)</div>', join, flags=re.S)]
qm = re.findall(r'<svg.*?</svg>', avatars[1], flags=re.S)[0]
frame_part = qm[:qm.index('<g')]
body_part = re.search(r'kw-avatar-body">(.*?)</g>', qm, flags=re.S).group(1)
# Under 48 px ModernAvatar zooms the body 1.2x and drops the shadow line
qm_small = re.findall(r'<svg.*?</svg>', avatars[0], flags=re.S)[0]
small_body = re.search(r'kw-avatar-body">(.*?)</g>', qm_small, flags=re.S).group(1)
transform = re.search(r'<g transform="([^"]*)"', qm_small).group(1)
thinking = re.findall(r'<svg.*?</svg>', avatars[6], flags=re.S)[1]
finished = re.findall(r'<svg.*?</svg>', avatars[10], flags=re.S)[1]

creature_names = ['Yellow antenna', 'Blue ears', 'Cyan visor', 'Green spikes', 'Coral beret', 'Red goggles',
                  'Mint bulb', 'Violet horns']
creatures = []
for name in creature_names:
    s = svg_after(join, f'aria-label="{name}"')
    creatures.append(rects(s))

icons = {
    'tick': svg_after(join, '<span class="tick">'),
    'plus': svg_after(join, '<div class="team new">'),
    'info': svg_after(join, '<div class="notice plain small"'),
    'lock': svg_after(play, '<div class="panel center" style="padding:28px 16px"><div style="color:var(--sky-300)">'),
    'check': svg_after(play, '<div class="source">'),
    'star': svg_after(play, 'border-color:var(--sky-600)"><div style="color:var(--sky-300)">'),
}

# Every table is built before PALETTE is printed: a colour first seen in a later table must be in it (pa5 round 2).
tables = {
    'QM_FRAME': rects(frame_part),
    'QM_BODY': rects(body_part),
    'QM_BODY_SMALL': rects(small_body),
    'MOOD_THINKING': rects(thinking),
    'MOOD_FINISHED': rects(finished),
}
icon_tables = {k: (vb(s), rects(s)) for k, s in icons.items()}
compact = dict(separators=(",", ":"))

print('// Generated by guest/tools/extract_art.py from pa0a guest mockups. Do not edit by hand.')
print('// A rect is [x, y, w, h, colour index into PALETTE] (-1 = currentColor).')
print('export type Rects = number[][];')
print(f'export const PALETTE: string[] = {json.dumps(palette)};')
for k in ('QM_FRAME', 'QM_BODY', 'QM_BODY_SMALL'):
    print(f'export const {k}: Rects = {json.dumps(tables[k], **compact)};')
print(f'export const QM_SMALL_TRANSFORM = {json.dumps(transform)};')
for k in ('MOOD_THINKING', 'MOOD_FINISHED'):
    print(f'export const {k}: Rects = {json.dumps(tables[k], **compact)};')
print(f'export const CREATURE_NAMES = {json.dumps(creature_names)};')
print(f'export const CREATURE_VIEWBOX = "5 1 16 20";')
print(f'export const CREATURES: Rects[] = {json.dumps(creatures, **compact)};')
print('export const ICONS: Record<string, [string, Rects]> = {')
for k, (box, rs) in icon_tables.items():
    print(f'  {k}: [{json.dumps(box)}, {json.dumps(rs, **compact)}],')
print('};')
