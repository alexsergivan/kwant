#!/usr/bin/env python3
"""Regenerates guest/src/wall/snap-art.ts from Mira's pa14 export (design READY, Mockup lint: PASS).

- Snap: the real ModernAvatar (snap style, pink body, `camera` overlay from pa14/src/snap-sprite.ts), taken from
  pa14/src/parts.json. Frame and mood badges are the Quizmaster's (art.ts QM_FRAME, MOOD_*), checked below, so only the
  body is new: the 64 px body and the 1.2x zoomed body ModernAvatar uses under 48 px.
- The pixel icons the wall screens use, from the patterns in pa14/src/gen.py (PXI): camera, photos, eye, retry, up,
  clock, plus.

Usage: python3 -I frontend/guest/tools/extract_snap.py <pa14 folder> > frontend/guest/src/wall/snap-art.ts
"""
import ast, json, re, sys

src = sys.argv[1]
parts = json.load(open(f'{src}/src/parts.json'))
gen = open(f'{src}/src/gen.py').read()
palette = []


def col(c):
    if c is None:
        return -1
    if c not in palette:
        palette.append(c)
    return palette.index(c)


def rects(svg):
    out = []
    for r in re.findall(r'<rect[^>]*>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', r))
        nums = [float(a[k]) for k in ('x', 'y', 'width', 'height')]
        nums = [int(n) if n == int(n) else n for n in nums]
        out.append(nums + [col(a.get('fill'))])
    return out


def body(svg):
    return re.search(r'kw-avatar-body">(.*?)</g></g>', svg, flags=re.S).group(1) if 'kw-avatar-body"><g' in svg else re.search(r'kw-avatar-body">(.*?)</g>', svg, flags=re.S).group(1)


big = parts['sn_64_idle']
small = parts['sn_28_idle']
frame = big[big.index('<svg'):big.index('<g')]
assert frame.count('<rect') == 24, 'Snap frame changed: compare with QM_FRAME'
transform = re.search(r'<g transform="([^"]*)"', small).group(1)

# The icon patterns: the PXI.update({...}) block in gen.py.
block = gen[gen.index('PXI.update(') + len('PXI.update('):]
block = block[:block.index('})') + 1]
pats = ast.literal_eval(block)


def icon(rows):
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == '#':
                s = x
                while x < len(row) and row[x] == '#':
                    x += 1
                out.append([s, y, x - s, 1, -1])
            else:
                x += 1
    return f'0 0 {max(len(r) for r in rows)} {len(rows)}', out


compact = dict(separators=(',', ':'))
print('// Generated by guest/tools/extract_snap.py from the pa14 export. Do not edit by hand.')
print('// A rect is [x, y, w, h, colour index into SN_PALETTE] (-1 = currentColor). Frame and mood badges: art.ts.')
print("import type { Rects } from '../art';")
b, s = rects(body(big)), rects(body(small))
print(f'export const SN_PALETTE: string[] = {json.dumps(palette)};')
print(f'export const SN_BODY: Rects = {json.dumps(b, **compact)};')
print(f'export const SN_BODY_SMALL: Rects = {json.dumps(s, **compact)};')
print(f'export const SN_SMALL_TRANSFORM = {json.dumps(transform)};')
print('export const WALL_ICONS: Record<string, [string, Rects]> = {')
for k in ('camera', 'photos', 'eye', 'retry', 'up', 'clock', 'plus'):
    vb, rs = icon(pats[k])
    print(f'  {k}: [{json.dumps(vb)}, {json.dumps(rs, **compact)}],')
print('};')
