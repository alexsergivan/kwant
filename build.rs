//! Embeds the built-in packs (`packs/<id>/`) into the binary, so nothing is read from disk for
//! them at run time. `packs/index.json` lists the pack ids in catalogue order; every folder in
//! `packs/` must be listed and every listed id must have a folder. The files are only embedded
//! here; `teams::packs` reads and checks them (the same check as `kwnt pack check`).

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn files_in(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())).map(|e| e.unwrap().path()).collect();
    entries.sort();
    for path in entries {
        let meta = fs::symlink_metadata(&path).unwrap();
        if meta.file_type().is_symlink() {
            panic!("{} is a link; a built-in pack holds only plain files", path.display());
        }
        if meta.is_dir() {
            files_in(root, &path, out);
        } else {
            let rel = path.strip_prefix(root).unwrap().components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/");
            out.push((rel, path));
        }
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let packs = manifest.join("packs");
    println!("cargo:rerun-if-changed=packs");
    println!("cargo:rerun-if-changed=build.rs");

    let index_text = fs::read_to_string(packs.join("index.json")).expect("packs/index.json lists the built-in packs");
    let index: Vec<String> = parse_index(&index_text);
    let mut folders: Vec<String> = fs::read_dir(&packs)
        .unwrap()
        .map(|e| e.unwrap())
        .filter(|e| e.file_type().unwrap().is_dir())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    folders.sort();
    for f in &folders {
        assert!(index.contains(f), "packs/{f}/ isn't listed in packs/index.json");
    }

    let mut code = String::from("/// One pack's files: (path in the pack, bytes).\npub type PackFiles = &'static [(&'static str, &'static [u8])];\n");
    code.push_str("/// Built-in packs, in catalogue order: (id, files). Generated by build.rs.\n");
    code.push_str("pub static BUILTIN_PACKS: &[(&str, PackFiles)] = &[\n");
    for id in &index {
        let dir = packs.join(id);
        assert!(dir.is_dir(), "packs/index.json lists {id}, but packs/{id}/ is missing");
        let mut files = Vec::new();
        files_in(&dir, &dir, &mut files);
        writeln!(code, "    ({id:?}, &[").unwrap();
        for (rel, path) in files {
            writeln!(code, "        ({rel:?}, include_bytes!({:?})),", path.to_string_lossy()).unwrap();
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("builtin_packs.rs");
    fs::write(out, code).unwrap();
}

/// `["inbox", "sales"]`: a JSON array of plain ids (no escapes), read without a JSON crate.
fn parse_index(text: &str) -> Vec<String> {
    let inner = text.trim().strip_prefix('[').and_then(|t| t.strip_suffix(']')).expect("packs/index.json is a JSON array of ids");
    let ids: Vec<String> = inner
        .split(',')
        .map(|s| s.trim())
        .filter(|s| !s.is_empty())
        .map(|s| {
            let id = s.strip_prefix('"').and_then(|s| s.strip_suffix('"')).expect("each id in packs/index.json is a string");
            assert!(!id.is_empty() && id.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-'), "bad pack id {id:?} in packs/index.json");
            id.to_string()
        })
        .collect();
    let mut seen = std::collections::HashSet::new();
    for id in &ids {
        assert!(seen.insert(id), "{id} is listed twice in packs/index.json");
    }
    ids
}
